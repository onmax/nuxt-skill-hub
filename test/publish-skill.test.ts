import { promises as fsp } from 'node:fs'
import { execSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { publishSkill } from '../src/generator'

let root: string
let generatedSkillRoot: string
const logger = { start: vi.fn(), success: vi.fn(), warn: vi.fn(), info: vi.fn() }

beforeEach(async () => {
  root = await fsp.mkdtemp(join(tmpdir(), 'skill-hub-publish-'))
  execSync('git init -q', { cwd: root })
  generatedSkillRoot = join(root, 'node_modules/.cache/nuxt-skill-hub/generated/nuxt-app')
  await fsp.mkdir(join(generatedSkillRoot, 'references/nuxt/rules'), { recursive: true })
  await fsp.writeFile(join(generatedSkillRoot, 'SKILL.md'), '# Nuxt Skill Router\n\n_Generated by nuxt-skill-hub. Do not edit this file manually._\n')
  await fsp.writeFile(join(generatedSkillRoot, 'references/nuxt/rules/plugins.md'), '## Plugins and Runtime Boot\n')
  await fsp.writeFile(join(generatedSkillRoot, '.gitignore'), '# generated\n*\n')
  await fsp.writeFile(join(root, '.gitignore'), 'node_modules\n')
  vi.clearAllMocks()
})

afterEach(async () => {
  await fsp.rm(root, { recursive: true, force: true })
})

function publish(targets: string[]) {
  return publishSkill({ logger, rootDir: root, exportRoot: root, skillName: 'nuxt-app', targets, generatedSkillRoot })
}

describe('publishSkill', () => {
  it('copies the whole tree for skill-folder agents and keeps it out of git', async () => {
    await publish(['claude-code'])

    const skillRoot = join(root, '.claude/skills/nuxt-app')
    await expect(fsp.readFile(join(skillRoot, 'SKILL.md'), 'utf8')).resolves.toContain('# Nuxt Skill Router')
    await expect(fsp.readFile(join(skillRoot, 'references/nuxt/rules/plugins.md'), 'utf8')).resolves.toContain('Plugins')
    expect(execSync('git status --porcelain', { cwd: root, encoding: 'utf8' }).trim()).toBe('?? .gitignore')
  })

  it('writes one pointer file for agents that load a rules directory', async () => {
    await publish(['cursor'])

    const pointerRoot = join(root, '.cursor/rules/nuxt-app')
    expect(await fsp.readdir(pointerRoot)).toEqual(['SKILL.md'])
    const pointer = await fsp.readFile(join(pointerRoot, 'SKILL.md'), 'utf8')
    expect(pointer).toContain('[the generated Nuxt skill](../../../node_modules/.cache/nuxt-skill-hub/generated/nuxt-app/SKILL.md)')
    expect(pointer).toContain('run `npx nuxt prepare` from the repository root')
  })

  it('replaces a wrapper from an older version but leaves a hand-written skill alone', async () => {
    const claudeRoot = join(root, '.claude/skills/nuxt-app')
    await fsp.mkdir(claudeRoot, { recursive: true })
    await fsp.writeFile(join(claudeRoot, 'SKILL.md'), '# Nuxt Skill Wrapper\n')
    const codexRoot = join(root, '.codex/skills/nuxt-app')
    await fsp.mkdir(codexRoot, { recursive: true })
    await fsp.writeFile(join(codexRoot, 'SKILL.md'), '# My own Nuxt notes\n')

    await publish(['claude-code', 'codex'])

    await expect(fsp.readFile(join(claudeRoot, 'SKILL.md'), 'utf8')).resolves.toContain('# Nuxt Skill Router')
    await expect(fsp.readFile(join(codexRoot, 'SKILL.md'), 'utf8')).resolves.toBe('# My own Nuxt notes\n')
    expect(logger.warn).toHaveBeenCalledWith(expect.stringContaining(`Skipped ${codexRoot}`))
  })

  it('writes once when two agents share a skills dir through a symlink', async () => {
    await fsp.mkdir(join(root, '.amp/skills'), { recursive: true })
    await fsp.mkdir(join(root, '.claude'), { recursive: true })
    await fsp.symlink('../.amp/skills', join(root, '.claude/skills'))

    await publish(['amp', 'claude-code'])

    expect((await fsp.readdir(join(root, '.amp/skills'))).sort()).toEqual(['nuxt-app'])
    await expect(fsp.readFile(join(root, '.claude/skills/nuxt-app/SKILL.md'), 'utf8')).resolves.toContain('# Nuxt Skill Router')
    expect(logger.warn).not.toHaveBeenCalled()
  })
})
